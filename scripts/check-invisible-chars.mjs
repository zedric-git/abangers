// Fails when a file in the repo contains a raw invisible or unusual-space
// character: a no-break space, a zero-width space, a byte order mark, a
// text-direction mark and the like (the full list is INVISIBLE_CHARACTERS
// below).
//
// These look like a normal space, or like nothing at all, in an editor
// and in a PR diff, so nobody can review them. That's how migration 0010
// got a regex full of characters nobody could read (#216): an AI tool
// wrote the raw characters instead of the escapes it meant. If code needs
// one of these characters, write it as an escape, which stays visible:
// \u00A0 in JS/TS strings and regexes, and inside a Postgres regex.
// Visible non-ASCII is fine: em dashes, arrows, ₱, full-width digits,
// emoji.
//
// Runs in `npm run check` and in CI.
//
// Usage:
//   node scripts/check-invisible-chars.mjs              # every file in the repo
//   node scripts/check-invisible-chars.mjs a.ts b.sql   # only these files
//
// "Every file in the repo" means the files git tracks, plus new files you
// haven't `git add`ed yet, minus the ones .gitignore ignores.

import { execFileSync } from "node:child_process";
import { readFileSync, statSync } from "node:fs";
import path from "node:path";

// The characters this check fails on, as
// [first code point, last code point, name shown in the report].
// Tab, newline, carriage return and the normal space are fine.
const INVISIBLE_CHARACTERS = [
  // Control characters, e.g. ESC from a pasted terminal color code.
  // (A NUL makes the whole file count as binary, so it's skipped.)
  [0x0001, 0x0008, "control character"],
  [0x000b, 0x000b, "vertical tab"],
  [0x000c, 0x000c, "form feed"],
  [0x000e, 0x001f, "control character"],
  [0x007f, 0x0084, "control character"],
  [0x0085, 0x0085, "next line (NEL)"],
  [0x0086, 0x009f, "control character"],

  // Spaces that aren't the normal space, and line breaks that aren't a
  // newline (VS Code calls those "unusual line terminators").
  [0x00a0, 0x00a0, "no-break space"],
  [0x1680, 0x1680, "Ogham space mark"],
  [0x2000, 0x200a, "special-width space (en, em, thin, hair, ...)"],
  [0x2028, 0x2028, "line separator"],
  [0x2029, 0x2029, "paragraph separator"],
  [0x202f, 0x202f, "narrow no-break space"],
  [0x205f, 0x205f, "medium mathematical space"],
  [0x3000, 0x3000, "ideographic (full-width) space"],

  // Zero-width characters.
  [0x00ad, 0x00ad, "soft hyphen"],
  [0x180e, 0x180e, "Mongolian vowel separator"],
  [0x200b, 0x200b, "zero-width space"],
  [0x200c, 0x200c, "zero-width non-joiner"],
  [0x200d, 0x200d, "zero-width joiner"], // allowed between two emoji, see isEmojiJoiner
  [0x2060, 0x2060, "word joiner"],
  [0x2061, 0x2064, "invisible math operator"],
  [0xfeff, 0xfeff, "zero-width no-break space (byte order mark)"],

  // Text-direction controls. They can make code display in a different
  // order than it runs ("Trojan Source", CVE-2021-42574).
  [0x061c, 0x061c, "Arabic letter mark (text direction)"],
  [0x200e, 0x200e, "left-to-right mark"],
  [0x200f, 0x200f, "right-to-left mark"],
  [0x202a, 0x202e, "text-direction embedding or override"],
  [0x2066, 0x2069, "text-direction isolate"],

  // Characters that show nothing at all and can hide text: an "invisible"
  // variable name, or instructions aimed at an AI tool reading the file.
  [0x115f, 0x1160, "Hangul filler (invisible letter)"],
  [0x3164, 0x3164, "Hangul filler (invisible letter)"],
  [0xffa0, 0xffa0, "halfwidth Hangul filler (invisible letter)"],
  [0xe0000, 0xe007f, "tag character (invisible text)"],
];

// Files this check doesn't read, and why. Keep the list short: nobody is
// warned about a raw character in one of these files.
const SKIPPED_FILES = [
  // Generated by npm, never edited by hand.
  "package-lock.json",
  // Lines 91, 93 and 95 hold raw characters, but 0010 is already applied,
  // so it can't be edited (check-migrations.mjs fails if it is). 0011
  // recreates the same policy with escapes (#216).
  "supabase/migrations/0010_require_verified_landlord_for_new_listings.sql",
];

// Repo root = one level up from this file (scripts/), so the check works
// from any folder.
const ROOT = path.resolve(import.meta.dirname, "..");

const ZERO_WIDTH_JOINER = 0x200d;
const BYTE_ORDER_MARK = 0xfeff;
// Variation selector 16 means "show this as an emoji" (e.g. in the red
// heart). It's invisible, but it belongs to the emoji, so it's allowed.
const EMOJI_STYLE = 0xfe0f;
// Pictographs plus the five skin-tone modifiers.
const EMOJI = /^[\p{Extended_Pictographic}\p{Emoji_Modifier}]$/u;

function isEmoji(char) {
  return (
    char !== undefined &&
    (EMOJI.test(char) || char.codePointAt(0) === EMOJI_STYLE)
  );
}

// A zero-width joiner between two emoji glues them into one: that's how
// the "woman technologist" emoji is built from a woman and a laptop. So
// it's allowed there, and flagged anywhere else.
function isEmojiJoiner(chars, i) {
  return isEmoji(chars[i - 1]) && isEmoji(chars[i + 1]);
}

function nameOf(codePoint) {
  const range = INVISIBLE_CHARACTERS.find(
    ([first, last]) => codePoint >= first && codePoint <= last,
  );
  return range?.[2];
}

// Every invisible character in `text`, as { line, column, codePoint, name }.
function findInvisibleCharacters(text) {
  const found = [];
  text.split("\n").forEach((line, index) => {
    // Array.from splits by whole characters, so an emoji is one item.
    const chars = Array.from(line);
    let column = 1;
    chars.forEach((char, i) => {
      const codePoint = char.codePointAt(0);
      const name = nameOf(codePoint);
      const allowed =
        codePoint === ZERO_WIDTH_JOINER && isEmojiJoiner(chars, i);
      if (name && !allowed) {
        found.push({ line: index + 1, column, codePoint, name });
      }
      // Columns count the way VS Code does: most emoji take 2.
      column += char.length;
    });
  });
  return found;
}

// The files named on the command line, or else every file in the repo
// (see the top of this file). -z separates the names with NUL, so git
// doesn't quote unusual file names.
function filesToCheck() {
  const named = process.argv.slice(2);
  if (named.length > 0) return named.map((file) => path.resolve(file));

  const output = execFileSync(
    "git",
    ["ls-files", "-z", "--cached", "--others", "--exclude-standard"],
    { cwd: ROOT, encoding: "utf8" },
  );
  // A Set, because a file with a merge conflict is listed once per side.
  const names = new Set(output.split("\0").filter(Boolean));
  return [...names].map((file) => path.join(ROOT, file));
}

// "src/app/page.tsx" for a file in the repo, the full path for any other.
function displayPath(fullPath) {
  const relative = path.relative(ROOT, fullPath);
  if (relative.startsWith("..") || path.isAbsolute(relative)) return fullPath;
  return relative.split(path.sep).join("/");
}

const plural = (count, word) => `${count} ${word}${count === 1 ? "" : "s"}`;

const problems = [];
let checkedCount = 0;

for (const fullPath of filesToCheck()) {
  const file = displayPath(fullPath);
  if (SKIPPED_FILES.includes(file)) continue;
  // Not a file: a deleted file git still lists, or a folder (git lists a
  // nested repository as "folder/").
  if (!statSync(fullPath, { throwIfNoEntry: false })?.isFile()) continue;
  const bytes = readFileSync(fullPath);
  // A NUL byte means a binary file (an image, a font): no text to check.
  if (bytes.includes(0)) continue;
  checkedCount++;

  const found = findInvisibleCharacters(bytes.toString("utf8"));
  for (const { line, column, codePoint, name } of found) {
    const code = "U+" + codePoint.toString(16).toUpperCase().padStart(4, "0");
    const startsFile =
      codePoint === BYTE_ORDER_MARK && line === 1 && column === 1;
    const description = startsFile
      ? "byte order mark (BOM): re-save the file as UTF-8 without BOM"
      : name;
    problems.push(`${file}:${line}:${column}  ${code} ${description}`);
  }
}

// --- Report -----------------------------------------------------------

if (problems.length > 0) {
  console.error(
    `check-invisible-chars failed: ` +
      `${plural(problems.length, "raw invisible or unusual-space character")}:\n`,
  );
  for (const problem of problems) console.error(`  ${problem}`);
  console.error(
    "\nThese look like a normal space, or like nothing at all, so nobody" +
      "\ncan see them in an editor or a PR diff. Delete them, or if the code" +
      "\nneeds the character, write it as an escape so it stays visible:" +
      "\n\\u00A0 in JS/TS strings and regexes, and inside a Postgres regex." +
      "\nSee AGENTS.md → Known gotchas.",
  );
  process.exit(1);
}

console.log(`check-invisible-chars: ${plural(checkedCount, "file")} OK.`);
